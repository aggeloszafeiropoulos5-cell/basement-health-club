create or replace function public.basement_promote_waiting(p_slot_id bigint)
returns bigint language plpgsql security definer set search_path='public','pg_temp' as $$
declare w basement_waiting_list%rowtype; v_id bigint; s basement_slots%rowtype; v_cfg jsonb; v_status text; v_member uuid; v_body text;
begin
  select coalesce(value,'{}') into v_cfg from app_settings where key='control_center_settings';
  if not coalesce((v_cfg->>'waitlistEnabled')::boolean,false) then return null; end if;
  select * into s from basement_slots where id=p_slot_id for update;
  if not found or not s.enabled or s.starts_at<=now() then return null; end if;
  if(select count(*) from basement_bookings where slot_id=s.id and status in('pending','booked'))>=s.capacity then return null; end if;
  v_status:=case when coalesce((v_cfg->>'autoConfirmWaitlist')::boolean,true) then 'booked' else 'pending' end;
  for w in select * from basement_waiting_list where slot_id=s.id and status='waiting' and coalesce(reason,'capacity')='capacity' order by created_at,id for update skip locked loop
    if not exists(select 1 from profiles where id=w.member_id and role='customer' and active) then continue; end if;
    begin
      insert into basement_bookings(slot_id,member_id,status,waitlist_source_id) values(s.id,w.member_id,v_status,w.id) returning id into v_id;
      update basement_waiting_list set status='promoted' where id=w.id;
      if coalesce((v_cfg->>'waitlistUpdateLink')::boolean,false) then
        select id into v_member from members where auth_user_id=w.member_id;
        v_body:=case when v_status='booked' then 'Άνοιξε το Member Portal: βρέθηκε θέση για '||s.service||'.'
          else 'Βρέθηκε θέση για '||s.service||'. Επιβεβαίωσέ την από το Member Portal μέσα σε '||coalesce((v_cfg->>'waitlistConfirmationHours')::integer,3)||' ώρες.' end;
        insert into outbound_notifications(member_id,channel,title,body,status,scheduled_at,template_key,booking_id)
        values(v_member,'push','Βρέθηκε θέση',v_body,'queued',now(),'waitlist_promoted',v_id);
      end if;
      return v_id;
    exception when sqlstate 'PBC01' or unique_violation then continue; end;
  end loop;
  return null;
end $$;
revoke all on function public.basement_promote_waiting(bigint) from public,anon,authenticated;

create or replace function public.basement_expire_waitlist_confirmations()
returns integer language plpgsql security definer set search_path='public','pg_temp' as $$
declare v_cfg jsonb; v_hours numeric; r record; v_count integer:=0;
begin
  if auth.uid() is null then raise exception 'Απαιτείται σύνδεση.'; end if;
  if not public.is_staff() then raise exception 'Δεν επιτρέπεται αυτή η ενέργεια.'; end if;
  select coalesce(value,'{}') into v_cfg from app_settings where key='control_center_settings';
  if coalesce((v_cfg->>'autoConfirmWaitlist')::boolean,true) then return 0; end if;
  v_hours:=greatest(.25,coalesce((v_cfg->>'waitlistConfirmationHours')::numeric,3));
  for r in
    select b.id,b.slot_id,w.id waiting_id
    from basement_bookings b join basement_waiting_list w on w.id=b.waitlist_source_id
    where b.status='pending' and w.status='promoted'
      and b.created_at<now()-make_interval(secs=>(v_hours*3600)::integer)
    order by b.created_at for update of b skip locked
  loop
    update basement_bookings set status='cancelled',cancelled_at=now() where id=r.id;
    update basement_waiting_list set status='expired' where id=r.waiting_id;
    v_count:=v_count+1;
    perform public.basement_promote_waiting(r.slot_id);
  end loop;
  return v_count;
end $$;
revoke all on function public.basement_expire_waitlist_confirmations() from public,anon;
grant execute on function public.basement_expire_waitlist_confirmations() to authenticated;


create or replace function public.basement_availability()
returns table(id bigint,service text,starts_at timestamptz,ends_at timestamptz,capacity integer,enabled boolean,reserved bigint)
language sql stable security definer set search_path='public','pg_temp' as $$
 with cfg as(select coalesce(value,'{}') v from app_settings where key='control_center_settings'),
 me as(
   select m.id,m.active,not exists(select 1 from member_packages x where x.member_id=m.id) is_new
   from profiles pr join members m on m.auth_user_id=pr.id
   where pr.id=auth.uid() and pr.active and pr.role='customer'
 )
 select s.id,s.service,s.starts_at,
 case when (select v->>'slotDurationMode' from cfg) ~ '^[0-9]+' then s.starts_at+make_interval(mins=>substring((select v->>'slotDurationMode' from cfg) from '^[0-9]+')::integer) else s.ends_at end,
 s.capacity,
 s.enabled
 and not(coalesce(((select v->>'holidayRestrictions' from cfg))::boolean,true) and exists(select 1 from closures c left join services sv2 on sv2.id=c.service_id where c.closure_date=(s.starts_at at time zone 'Europe/Athens')::date and(c.service_id is null or lower(sv2.name)=lower(s.service)) and(c.starts_at is null or(s.starts_at at time zone 'Europe/Athens')::time>=c.starts_at) and(c.ends_at is null or(s.starts_at at time zone 'Europe/Athens')::time<c.ends_at)))
 and (public.is_staff() or not coalesce((select (v->>'dependentAvailability')::boolean from cfg),false) or not exists(select 1 from basement_bookings b join basement_slots x on x.id=b.slot_id where b.member_id=auth.uid() and b.status in('pending','booked') and x.starts_at<s.ends_at and x.ends_at>s.starts_at))
 and (public.is_staff() or not exists(select 1 from me where basement_private.member_is_restricted(me.id,s.service,s.starts_at))),
 (select count(*) from basement_bookings b where b.slot_id=s.id and b.status in('pending','booked'))
 from basement_slots s left join services sv on lower(sv.name)=lower(s.service)
 where auth.uid() is not null
 and s.starts_at>=case when public.is_staff() then(now()-make_interval(days=>coalesce(((select v->>'adminVisibilityDays' from cfg))::integer,730))) else now() end
 and s.starts_at<case when nullif((select v->>'maxAvailableDate' from cfg),'') is not null then(((select v->>'maxAvailableDate' from cfg))::date+1)::timestamp at time zone 'Europe/Athens' else now()+make_interval(days=>coalesce(((select v->>'bookingMaxDays' from cfg))::integer,14)) end
 and(s.starts_at at time zone 'Europe/Athens')::time>=coalesce(nullif((select v->>'openingTime' from cfg),'')::time,'00:00')
 and(s.starts_at at time zone 'Europe/Athens')::time<=coalesce(nullif((select v->>'closingTime' from cfg),'')::time,'23:59')
 and(public.is_staff() or(
   sv.active and sv.online_booking_enabled
   and basement_private.member_service_allowed(s.service,(s.starts_at at time zone 'Europe/Athens')::date)
   and not coalesce((select (v->>'pauseBookings')::boolean from cfg),false)
   and (
     exists(select 1 from me where is_new and coalesce((select (v->>'newCustomerBooking')::boolean from cfg),false))
     or exists(select 1 from me where not is_new and coalesce((select (v->>'existingCustomerBooking')::boolean from cfg),true))
   )
   and s.starts_at>=now()+make_interval(secs=>(coalesce((select (v->>'bookingMinHours')::numeric from cfg),0)*3600)::integer)
   and s.starts_at<=now()+make_interval(days=>coalesce((select (v->>'bookingMaxDays')::integer from cfg),14))
   and not((s.starts_at at time zone 'Europe/Athens')::date=(now() at time zone 'Europe/Athens')::date+1 and(now() at time zone 'Europe/Athens')::time>coalesce(nullif((select v->>'previousDayDeadline' from cfg),'')::time,'23:59'))
 ))
 order by s.starts_at,s.service;
$$;
