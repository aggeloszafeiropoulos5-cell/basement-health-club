create or replace function basement_private.next_booking_position(p_slot bigint,p_capacity integer)
returns integer language plpgsql security definer set search_path='' as $$
declare i integer; v_cfg jsonb;
begin
  select coalesce(value,'{}') into v_cfg from public.app_settings where key='control_center_settings';
  if not coalesce((v_cfg->>'fixedPositions')::boolean,false) then return null; end if;
  perform pg_advisory_xact_lock(p_slot);
  for i in 1..greatest(1,p_capacity) loop
    if not exists(select 1 from public.basement_bookings b where b.slot_id=p_slot and b.position_no=i and b.status in('pending','booked')) then return i; end if;
  end loop;
  if coalesce((v_cfg->>'fixedPositionsAffectCapacity')::boolean,false) then return null; end if;
  select coalesce(max(position_no),p_capacity,0)+1 into i from public.basement_bookings where slot_id=p_slot and status in('pending','booked');
  return i;
end $$;
revoke all on function basement_private.next_booking_position(bigint,integer) from public,anon,authenticated;

create or replace function basement_private.assign_booking_position()
returns trigger language plpgsql security definer set search_path='' as $$
declare v_cfg jsonb; v_capacity integer; v_pos integer;
begin
  select coalesce(value,'{}') into v_cfg from public.app_settings where key='control_center_settings';
  if not coalesce((v_cfg->>'fixedPositions')::boolean,false) then new.position_no:=null; return new; end if;
  if new.status not in('pending','booked') then return new; end if;
  if tg_op='INSERT' then
    select capacity into v_capacity from public.basement_slots where id=new.slot_id;
    v_pos:=basement_private.next_booking_position(new.slot_id,coalesce(v_capacity,1));
    if v_pos is null then raise exception 'Δεν υπάρχει ελεύθερη σταθερή θέση.'; end if;
    new.position_no:=v_pos;
  elsif new.slot_id is distinct from old.slot_id or old.status not in('pending','booked') then
    select capacity into v_capacity from public.basement_slots where id=new.slot_id;
    v_pos:=basement_private.next_booking_position(new.slot_id,coalesce(v_capacity,1));
    if v_pos is null then raise exception 'Δεν υπάρχει ελεύθερη σταθερή θέση.'; end if;
    new.position_no:=v_pos;
  end if;
  return new;
end $$;
revoke all on function basement_private.assign_booking_position() from public,anon,authenticated;
drop trigger if exists assign_booking_position on public.basement_bookings;
create trigger assign_booking_position before insert or update of slot_id,status on public.basement_bookings
for each row execute function basement_private.assign_booking_position();


create or replace function basement_private.sync_fixed_positions()
returns void language plpgsql security definer set search_path='' as $$
declare v_cfg jsonb;
begin
  select coalesce(value,'{}') into v_cfg from public.app_settings where key='control_center_settings';
  if not coalesce((v_cfg->>'fixedPositions')::boolean,false) then return; end if;
  with ranked as(
    select b.id,row_number() over(partition by b.slot_id order by b.created_at,b.id)::integer as pos
    from public.basement_bookings b join public.basement_slots s on s.id=b.slot_id
    where b.status in('pending','booked') and s.ends_at>now()
  )
  update public.basement_bookings b set position_no=r.pos from ranked r where b.id=r.id and b.position_no is distinct from r.pos;
end $$;
revoke all on function basement_private.sync_fixed_positions() from public,anon,authenticated;

