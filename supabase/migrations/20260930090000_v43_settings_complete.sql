create or replace function basement_private.queue_waiting(p_slot bigint,p_member_auth uuid,p_reason text default 'capacity')
returns bigint language plpgsql security definer set search_path='' as $$
declare v_id bigint; v_cfg jsonb; v_member uuid; v_wait_count integer; v_service text; v_start timestamptz; v_body text;
begin
  select coalesce(value,'{}') into v_cfg from public.app_settings where key='control_center_settings';
  if not coalesce((v_cfg->>'waitlistEnabled')::boolean,false) then raise exception 'Η λίστα αναμονής είναι απενεργοποιημένη.'; end if;
  select id into v_member from public.members where auth_user_id=p_member_auth;
  if v_member is null then raise exception 'Δεν βρέθηκε καρτέλα μέλους.'; end if;
  select count(*) into v_wait_count from public.basement_waiting_list where member_id=p_member_auth and status='waiting';
  if v_wait_count>=coalesce((v_cfg->>'waitlistLimit')::integer,2) then raise exception 'Συμπληρώθηκε το όριο λίστας αναμονής.'; end if;
  insert into public.basement_waiting_list(slot_id,member_id,status,reason)
  values(p_slot,p_member_auth,'waiting',coalesce(nullif(p_reason,''),'capacity'))
  on conflict(slot_id,member_id,status) do update set created_at=excluded.created_at,reason=excluded.reason returning id into v_id;
  if coalesce((v_cfg->>'waitlistUpdateLink')::boolean,false) then
    select service,starts_at into v_service,v_start from public.basement_slots where id=p_slot;
    v_body:='Μπήκες στη λίστα αναμονής για '||coalesce(v_service,'προπόνηση')||'. Άνοιξε το Member Portal για ενημέρωση της θέσης σου.';
    insert into public.outbound_notifications(member_id,channel,title,body,status,scheduled_at,template_key)
    values(v_member,'push','Λίστα αναμονής',v_body,'queued',now(),'waitlist_joined');
  end if;
  return -v_id;
end $$;
revoke all on function basement_private.queue_waiting(bigint,uuid,text) from public,anon,authenticated;

