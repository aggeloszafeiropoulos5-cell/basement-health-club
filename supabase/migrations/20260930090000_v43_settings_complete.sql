declare
  v_actor uuid:=auth.uid(); v_role text; v_target uuid; v_slot public.basement_slots%rowtype;
  v_cfg jsonb:='{}'; v_is_admin boolean; v_member uuid; v_member_active boolean; v_is_new boolean; v_skip_new boolean;
  v_service public.services%rowtype; v_count integer; v_id bigint; v_status text; v_over_limit boolean:=false; v_limit_message text:='';
  v_package public.member_packages%rowtype; v_template public.package_templates%rowtype;
  v_local_start timestamp; v_now_local timestamp:=now() at time zone 'Europe/Athens';
  v_no_show_count integer; v_limit integer; v_unlock_cost integer; v_last_unlock integer; v_active_limit integer; v_enforce_limits boolean;
begin
  if v_actor is null then raise exception 'Απαιτείται σύνδεση.'; end if;
  select role::text into v_role from profiles where id=v_actor and active;
  if v_role is null then raise exception 'Απαιτείται ενεργή σύνδεση.'; end if;
  v_is_admin:=coalesce(v_role,'') in('owner','admin','reception'); v_target:=coalesce(p_member_id,v_actor);
  if v_target<>v_actor and not v_is_admin then raise exception 'Δεν επιτρέπεται κράτηση για άλλο μέλος.'; end if;
  if not exists(select 1 from profiles where id=v_target and role='customer' and active) then raise exception 'Δεν βρέθηκε ενεργό μέλος.'; end if;
  select coalesce(value,'{}') into v_cfg from app_settings where key='control_center_settings';
  v_enforce_limits:=not v_is_admin or not coalesce((v_cfg->>'adminExceedsLimits')::boolean,true);
  if not v_is_admin and coalesce((v_cfg->>'pauseBookings')::boolean,false) then raise exception 'Οι νέες κρατήσεις είναι προσωρινά κλειστές.'; end if;

  select * into v_slot from basement_slots where id=p_slot_id for update;
  if not found or not v_slot.enabled then raise exception 'Η ώρα δεν είναι διαθέσιμη.'; end if;
  v_local_start:=v_slot.starts_at at time zone 'Europe/Athens';
  if v_slot.starts_at<=now() then raise exception 'Η ώρα έχει ήδη ξεκινήσει.'; end if;
  if not v_is_admin and v_slot.starts_at<now()+make_interval(secs=>(coalesce((v_cfg->>'bookingMinHours')::numeric,0)*3600)::integer) then raise exception 'Η κράτηση πρέπει να γίνει νωρίτερα σύμφωνα με την πολιτική κρατήσεων.'; end if;
  if not v_is_admin and v_slot.starts_at>now()+make_interval(days=>coalesce((v_cfg->>'bookingMaxDays')::integer,14)) then raise exception 'Η ημερομηνία είναι έξω από το επιτρεπόμενο διάστημα κρατήσεων.'; end if;
  if nullif(v_cfg->>'maxAvailableDate','') is not null and v_local_start::date>(v_cfg->>'maxAvailableDate')::date then raise exception 'Η ημερομηνία δεν είναι διαθέσιμη.'; end if;
  if not v_is_admin and v_local_start::date=v_now_local::date+1 and v_now_local::time>coalesce(nullif(v_cfg->>'previousDayDeadline','')::time,'23:59') then raise exception 'Έληξε η προθεσμία κράτησης για την επόμενη ημέρα.'; end if;
  if v_local_start::time<coalesce(nullif(v_cfg->>'openingTime','')::time,'00:00') or v_local_start::time>coalesce(nullif(v_cfg->>'closingTime','')::time,'23:59') then raise exception 'Η ώρα είναι εκτός ωραρίου λειτουργίας.'; end if;

  select * into v_service from services where lower(name)=lower(v_slot.service) limit 1;
  if found and not v_is_admin and (not v_service.active or not v_service.online_booking_enabled) then raise exception 'Η υπηρεσία δεν δέχεται online κρατήσεις.'; end if;
  if coalesce((v_cfg->>'holidayRestrictions')::boolean,true) and exists(select 1 from closures c where c.closure_date=v_local_start::date and(c.service_id is null or c.service_id=v_service.id) and(c.starts_at is null or v_local_start::time>=c.starts_at) and(c.ends_at is null or v_local_start::time<c.ends_at)) then raise exception 'Η επιλεγμένη ώρα είναι κλειστή λόγω αργίας ή ειδικού ωραρίου.'; end if;

  select id,active into v_member,v_member_active from members where auth_user_id=v_target;
  if v_member is null then raise exception 'Δεν βρέθηκε καρτέλα μέλους.'; end if;
  v_is_new:=not exists(select 1 from member_packages where member_id=v_member);
  v_skip_new:=v_is_new and coalesce((v_cfg->>'newCustomerBooking')::boolean,false) and coalesce((v_cfg->>'skipNewCustomerChecks')::boolean,false);
  if not v_is_admin and v_is_new and not coalesce((v_cfg->>'newCustomerBooking')::boolean,false) then raise exception 'Οι κρατήσεις νέων μελών είναι απενεργοποιημένες.'; end if;
  if not v_is_admin and not v_is_new and not coalesce((v_cfg->>'existingCustomerBooking')::boolean,true) then raise exception 'Οι online κρατήσεις υπαρχόντων μελών είναι απενεργοποιημένες.'; end if;
  if not v_is_admin and coalesce((v_cfg->>'activeCustomersOnly')::boolean,true) and not coalesce(v_member_active,false) then raise exception 'Απαιτείται ενεργό μέλος.'; end if;
  if not v_is_admin and coalesce((v_cfg->>'gdprConsent')::boolean,false) and not exists(select 1 from member_consents where member_id=v_member and consent_key='booking_gdpr') then raise exception 'Χρειάζεται αποδοχή όρων/GDPR πριν από την κράτηση.'; end if;
  if not v_is_admin and basement_private.member_is_restricted(v_member,v_slot.service,v_slot.starts_at) then raise exception 'Υπάρχει περιορισμός κράτησης για αυτή την υπηρεσία ή ώρα.'; end if;
  if exists(select 1 from basement_bookings where slot_id=p_slot_id and member_id=v_target and status in('pending','booked')) then raise exception 'Το μέλος έχει ήδη κράτηση σε αυτή την ώρα.'; end if;
  if (not v_is_admin and coalesce((v_cfg->>'dependentAvailability')::boolean,false)) or not coalesce((v_cfg->>'allowDoubleBooking')::boolean,false) or not coalesce((v_cfg->>'overlapAvailability')::boolean,true) then
    if exists(select 1 from basement_bookings b join basement_slots s on s.id=b.slot_id where b.member_id=v_target and b.status in('pending','booked') and s.starts_at<v_slot.ends_at and s.ends_at>v_slot.starts_at) then raise exception 'Υπάρχει ήδη κράτηση που επικαλύπτει αυτή την ώρα.'; end if;
  end if;

  select mp.* into v_package from member_packages mp where mp.member_id=v_member and mp.status::text in('active','scheduled') and mp.starts_on<=v_local_start::date
    and (not coalesce((v_cfg->>'blockAfterExpiry')::boolean,true) or mp.expires_on+coalesce((v_cfg->>'maxAutoExtendDays')::integer,0)>=v_local_start::date)
    and (mp.frozen_until is null or mp.frozen_until<v_local_start::date) and (mp.sessions_remaining is null or mp.sessions_remaining>0)
    and basement_private.package_covers_service(mp.package_template_id,v_slot.service)
    order by mp.expires_on,mp.created_at limit 1;

  if not v_is_admin and v_is_new and v_package.id is null and not v_skip_new and not coalesce((v_cfg->>'newCustomerOutsideSubscription')::boolean,false) then raise exception 'Χρειάζεται ενεργή συνδρομή πριν από την πρώτη online κράτηση.'; end if;
  if not v_is_admin and not v_skip_new and coalesce((v_cfg->>'creditsRequired')::boolean,true) and v_package.id is null and not (v_is_new and coalesce((v_cfg->>'newCustomerOutsideSubscription')::boolean,false)) then
    select count(*) into v_count from basement_bookings where member_id=v_target and status in('pending','booked') and created_at>=date_trunc('month',now());
    if v_count>=coalesce((v_cfg->>'bookingsWithoutCredits')::integer,0) then raise exception 'Δεν υπάρχουν διαθέσιμες συνεδρίες ή ενεργό πακέτο.'; end if;
  end if;

  if not v_is_admin and not v_skip_new and not (coalesce((v_cfg->>'subscriptionOnly')::boolean,false) and v_package.id is null) then
    v_limit:=coalesce((v_cfg->>'noShowLimit')::integer,0);
    if v_limit>0 then
      select count(*) into v_no_show_count from basement_bookings where member_id=v_target and status='no_show';
      if v_no_show_count>=v_limit then
        select coalesce(max(no_show_count),0) into v_last_unlock from member_no_show_unlocks where member_id=v_member;
        if v_last_unlock<v_no_show_count then
          v_unlock_cost:=coalesce((v_cfg->>'noShowUnlockCost')::integer,0);
          if v_unlock_cost<=0 then raise exception 'Το όριο απουσιών έχει συμπληρωθεί. Επικοινώνησε με το γυμναστήριο.'; end if;
          if v_package.id is null or (v_package.sessions_remaining is not null and v_package.sessions_remaining<v_unlock_cost) then raise exception 'Χρειάζονται % διαθέσιμες συνεδρίες για ξεκλείδωμα μετά από απουσίες.',v_unlock_cost; end if;
          if v_package.sessions_remaining is not null then update member_packages set sessions_remaining=sessions_remaining-v_unlock_cost where id=v_package.id returning * into v_package; end if;
          insert into member_no_show_unlocks(member_id,no_show_count,cost,member_package_id) values(v_member,v_no_show_count,v_unlock_cost,v_package.id);
        end if;
      end if;
    end if;
  end if;

  if v_enforce_limits and not v_skip_new and not (coalesce((v_cfg->>'subscriptionOnly')::boolean,false) and v_package.id is null) then
    if v_package.id is not null then
      select * into v_template from package_templates where id=v_package.package_template_id;
      if coalesce(v_template.max_bookings_day,0)>0 and (select count(*) from basement_bookings b join basement_slots s on s.id=b.slot_id where b.member_id=v_target and basement_private.booking_counts_for_limit(b.status,b.moved_at,v_cfg) and (s.starts_at at time zone 'Europe/Athens')::date=v_local_start::date and (not coalesce((v_cfg->>'serviceBookingLimits')::boolean,false) or lower(s.service)=lower(v_slot.service)))>=v_template.max_bookings_day then v_over_limit:=true;v_limit_message:='Συμπληρώθηκε το ημερήσιο όριο κρατήσεων.'; end if;
      if not v_over_limit and coalesce(v_template.max_bookings_week,0)>0 and (select count(*) from basement_bookings b join basement_slots s on s.id=b.slot_id where b.member_id=v_target and basement_private.booking_counts_for_limit(b.status,b.moved_at,v_cfg) and date_trunc('week',s.starts_at at time zone 'Europe/Athens')=date_trunc('week',v_local_start) and (not coalesce((v_cfg->>'serviceBookingLimits')::boolean,false) or lower(s.service)=lower(v_slot.service)))>=v_template.max_bookings_week then v_over_limit:=true;v_limit_message:='Συμπληρώθηκε το εβδομαδιαίο όριο κρατήσεων.'; end if;
    end if;
    v_limit:=coalesce((v_cfg->>'maxBookingsPerPeriod')::integer,0);
    if not v_over_limit and v_limit>0 and (select count(*) from basement_bookings b join basement_slots s on s.id=b.slot_id where b.member_id=v_target and basement_private.booking_counts_for_limit(b.status,b.moved_at,v_cfg) and date_trunc('week',s.starts_at at time zone 'Europe/Athens')=date_trunc('week',v_local_start) and (not coalesce((v_cfg->>'serviceBookingLimits')::boolean,false) or lower(s.service)=lower(v_slot.service)))>=v_limit then v_over_limit:=true;v_limit_message:='Συμπληρώθηκε το εβδομαδιαίο όριο κρατήσεων.'; end if;
    v_active_limit:=coalesce((v_cfg->>'maxActiveBookings')::integer,0);
    if not v_over_limit and v_active_limit>0 and (select count(*) from basement_bookings b join basement_slots s on s.id=b.slot_id where b.member_id=v_target and b.status in('pending','booked') and s.ends_at>now())>=v_active_limit then v_over_limit:=true;v_limit_message:='Συμπληρώθηκε το όριο ενεργών κρατήσεων.'; end if;
  end if;
  if v_over_limit then
    if coalesce((v_cfg->>'overLimitToWaitlist')::boolean,false) and coalesce((v_cfg->>'waitlistEnabled')::boolean,false) and coalesce(v_service.waiting_list_enabled,true) then return basement_private.queue_waiting(p_slot_id,v_target,'limit'); end if;
    raise exception '%',v_limit_message;
  end if;

  select count(*) into v_count from basement_bookings where slot_id=p_slot_id and status in('pending','booked');
  if v_count>=v_slot.capacity or (not coalesce((v_cfg->>'autoConfirm')::boolean,true) and coalesce((v_cfg->>'unconfirmedToWaitlist')::boolean,false)) then
    if not coalesce((v_cfg->>'waitlistEnabled')::boolean,false) or (v_service.id is not null and not v_service.waiting_list_enabled) then raise exception 'Οι θέσεις εξαντλήθηκαν.'; end if;
    return basement_private.queue_waiting(p_slot_id,v_target,'capacity');
  end if;
  v_status:=case when coalesce((v_cfg->>'autoConfirm')::boolean,true) or (coalesce((v_cfg->>'autoConfirmExisting')::boolean,false) and v_package.id is not null) then 'booked' else 'pending' end;
  insert into basement_bookings(slot_id,member_id,status,credit_policy) values(p_slot_id,v_target,v_status,case when v_package.id is null then 'legacy' else 'booking' end) returning id into v_id;
  return v_id;
end $$;
revoke all on function public.basement_book(bigint,uuid) from public,anon;
grant execute on function public.basement_book(bigint,uuid) to authenticated;

create or replace function public.basement_cancel(p_booking_id bigint)
returns void language plpgsql security definer set search_path='public','pg_temp' as $$
declare b public.basement_bookings%rowtype; v_role text; v_admin boolean; v_start timestamptz; v_slot bigint; v_cfg jsonb; v_limit integer; v_actions integer; v_late boolean; v_late_count integer;
begin
  select role::text into v_role from profiles where id=auth.uid() and active;
  if v_role is null then raise exception 'Απαιτείται ενεργή σύνδεση.'; end if;
  v_admin:=v_role in('owner','admin','reception');
  select coalesce(value,'{}') into v_cfg from app_settings where key='control_center_settings';
  select * into b from basement_bookings where id=p_booking_id for update;
  if not found then raise exception 'Η κράτηση δεν βρέθηκε.'; end if;
  select starts_at into v_start from basement_slots where id=b.slot_id for update; v_slot:=b.slot_id;
  if b.member_id<>auth.uid() and not v_admin then raise exception 'Δεν επιτρέπεται η ακύρωση.'; end if;
  if b.status in('cancelled','late_cancel') then return; end if;
  if b.status not in('pending','booked') then raise exception 'Η κράτηση δεν είναι ενεργή.'; end if;
  if v_start<=now() and not v_admin then raise exception 'Η προπόνηση έχει ήδη ξεκινήσει.'; end if;

  if not v_admin then
    v_limit:=coalesce((v_cfg->>'cancelMoveLimit')::integer,0);
    if v_limit>0 then
      select (select count(*) from basement_bookings x where x.member_id=b.member_id and x.cancelled_at>=date_trunc('month',now()))+
             (select count(*) from basement_bookings x where x.member_id=b.member_id and x.moved_at>=date_trunc('month',now())) into v_actions;
      if v_actions>=v_limit then raise exception 'Συμπληρώθηκε το όριο ακυρώσεων/μεταφορών για τον μήνα.'; end if;
    end if;
  end if;

  v_late:=v_start<=now() or v_start<now()+make_interval(mins=>coalesce((v_cfg->>'cancelMinMinutes')::integer,0));
  if v_late and not v_admin then
    select count(*) into v_late_count from basement_bookings where member_id=b.member_id and status='late_cancel' and cancelled_at>=date_trunc('month',now());
    if v_late_count>=coalesce((v_cfg->>'lateCancelAllowedCount')::integer,0) then raise exception 'Έληξε η προθεσμία ακύρωσης.'; end if;
  end if;

  update basement_bookings set status=case when v_late then 'late_cancel' else 'cancelled' end,cancelled_at=now() where id=b.id;
  perform public.basement_promote_waiting(v_slot);
end $$;
revoke all on function public.basement_cancel(bigint) from public,anon;
grant execute on function public.basement_cancel(bigint) to authenticated;

create or replace function public.basement_move_booking(p_booking_id bigint,p_new_slot_id bigint)
returns void language plpgsql security definer set search_path='public','pg_temp' as $$
declare b basement_bookings%rowtype; old_s basement_slots%rowtype; new_s basement_slots%rowtype; v_cfg jsonb:='{}'; v_role text; v_admin boolean; v_count integer; v_new_status text; v_limit integer; v_actions integer; v_member uuid;
begin
  if auth.uid() is null then raise exception 'Απαιτείται σύνδεση.'; end if;
  select role::text into v_role from profiles where id=auth.uid() and active; v_admin:=coalesce(v_role,'') in('owner','admin','reception');
  select coalesce(value,'{}') into v_cfg from app_settings where key='control_center_settings';
  if not v_admin and coalesce((v_cfg->>'disableCustomerMove')::boolean,false) then raise exception 'Η μεταφορά από μέλη είναι απενεργοποιημένη.'; end if;
  select * into b from basement_bookings where id=p_booking_id for update; if not found or b.status not in('pending','booked') then raise exception 'Η κράτηση δεν είναι ενεργή.'; end if;
  if b.member_id<>auth.uid() and not v_admin then raise exception 'Δεν επιτρέπεται η μεταφορά.'; end if;
  select * into old_s from basement_slots where id=b.slot_id; select * into new_s from basement_slots where id=p_new_slot_id for update;
  if not found or not new_s.enabled then raise exception 'Η νέα ώρα δεν είναι διαθέσιμη.'; end if;
  if new_s.starts_at<=now() and not(v_admin and coalesce((v_cfg->>'moveToPastAdmin')::boolean,false)) then raise exception 'Δεν επιτρέπεται μεταφορά στο παρελθόν.'; end if;
  if not v_admin and old_s.starts_at<now()+make_interval(secs=>(coalesce((v_cfg->>'moveMinHours')::numeric,0)*3600)::integer) then raise exception 'Έληξε η προθεσμία μεταφοράς.'; end if;
  if not coalesce((v_cfg->>'changeServiceOnMove')::boolean,false) and new_s.service<>old_s.service then raise exception 'Δεν επιτρέπεται αλλαγή υπηρεσίας στη μεταφορά.'; end if;
  select id into v_member from members where auth_user_id=b.member_id;
  if not v_admin and basement_private.member_is_restricted(v_member,new_s.service,new_s.starts_at) then raise exception 'Υπάρχει περιορισμός κράτησης για τη νέα ώρα.'; end if;
  if not v_admin then
    v_limit:=coalesce((v_cfg->>'cancelMoveLimit')::integer,0);
    if v_limit>0 then select (select count(*) from basement_bookings x where x.member_id=b.member_id and x.cancelled_at>=date_trunc('month',now()))+(select count(*) from basement_bookings x where x.member_id=b.member_id and x.moved_at>=date_trunc('month',now())) into v_actions; if v_actions>=v_limit then raise exception 'Συμπληρώθηκε το όριο ακυρώσεων/μεταφορών για τον μήνα.'; end if; end if;
  end if;
  select count(*) into v_count from basement_bookings where slot_id=p_new_slot_id and status in('pending','booked'); if v_count>=new_s.capacity then raise exception 'Η νέα ώρα είναι πλήρης.'; end if;
  if exists(select 1 from basement_bookings where slot_id=p_new_slot_id and member_id=b.member_id and status in('pending','booked') and id<>p_booking_id) then raise exception 'Υπάρχει ήδη κράτηση στη νέα ώρα.'; end if;
  v_new_status:=case when coalesce((v_cfg->>'keepStatusOnMove')::boolean,true) then b.status else 'booked' end;
  update basement_bookings set slot_id=p_new_slot_id,status=v_new_status,moved_at=now(),moved_from_slot_id=b.slot_id where id=p_booking_id;
  perform public.basement_promote_waiting(b.slot_id);
end $$;
revoke all on function public.basement_move_booking(bigint,bigint) from public,anon;
grant execute on function public.basement_move_booking(bigint,bigint) to authenticated;

create or replace function public.basement_confirm_booking(p_booking_id bigint)
returns void language plpgsql security definer set search_path='public','pg_temp' as $$
declare b basement_bookings%rowtype; v_cfg jsonb; v_hours numeric; v_role text;
begin
  if auth.uid() is null then raise exception 'Απαιτείται σύνδεση.'; end if;
  select role::text into v_role from profiles where id=auth.uid() and active;
  select * into b from basement_bookings where id=p_booking_id for update;
  if not found or b.status<>'pending' then raise exception 'Η κράτηση δεν είναι σε αναμονή επιβεβαίωσης.'; end if;
  if b.member_id<>auth.uid() and coalesce(v_role,'') not in('owner','admin','reception') then raise exception 'Δεν επιτρέπεται η επιβεβαίωση.'; end if;
  if b.member_id=auth.uid() and b.waitlist_source_id is null and coalesce(v_role,'')='customer' then raise exception 'Η κράτηση περιμένει επιβεβαίωση από το γυμναστήριο.'; end if;
  select coalesce(value,'{}') into v_cfg from app_settings where key='control_center_settings';
  if b.waitlist_source_id is not null then
    v_hours:=greatest(.25,coalesce((v_cfg->>'waitlistConfirmationHours')::numeric,3));
    if b.created_at<now()-make_interval(secs=>(v_hours*3600)::integer) then
      update basement_bookings set status='cancelled',cancelled_at=now() where id=b.id;
      update basement_waiting_list set status='expired' where id=b.waitlist_source_id;
      perform public.basement_promote_waiting(b.slot_id);
      raise exception 'Η προθεσμία επιβεβαίωσης έληξε και η θέση δόθηκε στον επόμενο.';
    end if;
    update basement_waiting_list set status='accepted' where id=b.waitlist_source_id;
  end if;
  update basement_bookings set status='booked' where id=b.id;
end $$;
revoke all on function public.basement_confirm_booking(bigint) from public,anon;
grant execute on function public.basement_confirm_booking(bigint) to authenticated;

create or replace function public.basement_admin_booking_action(p_booking_id bigint,p_action text)
returns void language plpgsql security definer set search_path='public','pg_temp' as $$
declare v_role text; b public.basement_bookings%rowtype; v_member uuid; v_cfg jsonb; v_slot bigint; v_capacity integer;
begin
  select role::text into v_role from public.profiles where id=auth.uid() and active;
  if coalesce(v_role,'') not in('owner','admin','reception') then raise exception 'Δεν επιτρέπεται αυτή η ενέργεια.'; end if;
  select slot_id into v_slot from public.basement_bookings where id=p_booking_id;
  select capacity into v_capacity from public.basement_slots where id=v_slot for update;
  select * into b from public.basement_bookings where id=p_booking_id for update;
  if not found then raise exception 'Η κράτηση δεν βρέθηκε.'; end if;
  if b.slot_id<>v_slot then raise exception 'Η κράτηση μεταφέρθηκε. Ανανέωσε και δοκίμασε ξανά.'; end if;
  select coalesce(value,'{}') into v_cfg from public.app_settings where key='control_center_settings';
  select id into v_member from public.members where auth_user_id=b.member_id;
  if p_action in('complete','no_show') then
    if b.status not in('pending','booked','completed','no_show') then raise exception 'Κάνε πρώτα αναίρεση της ακύρωσης.'; end if;
    update public.basement_bookings set status=case when p_action='complete' then 'completed' else 'no_show' end,
      completed_at=coalesce(completed_at,now()),checked_in_at=case when p_action='complete' then coalesce(checked_in_at,now()) else null end where id=b.id;
    if p_action='complete' and v_member is not null and coalesce((v_cfg->>'checkIn')::boolean,true) then
      insert into public.gym_checkins(member_id,booking_id,method,notes) values(v_member,b.id,'automatic','Ολοκλήρωση ραντεβού') on conflict do nothing;
    elsif p_action='no_show' then delete from public.gym_checkins where booking_id=b.id; end if;
  elsif p_action='confirm' then update public.basement_bookings set status='booked' where id=b.id and status='pending';
  elsif p_action='pending' then update public.basement_bookings set status='pending' where id=b.id and status='booked';
  elsif p_action='paid' then update public.basement_bookings set payment_status='paid',paid_at=case when coalesce((v_cfg->>'paidDate')::boolean,true) then coalesce(paid_at,now()) else null end where id=b.id;
  elsif p_action='unpaid' then update public.basement_bookings set payment_status='unpaid',paid_at=null where id=b.id;
  elsif p_action='undo' then
    if b.status in('pending','booked') then return; end if;
    if (select count(*) from public.basement_bookings where slot_id=b.slot_id and status in('pending','booked') and id<>b.id)>=v_capacity then raise exception 'Η ώρα είναι πλήρης. Δεν έγινε αναίρεση.'; end if;
    update public.basement_bookings set status='booked',completed_at=null,checked_in_at=null,cancelled_at=null,
      credit_policy=case when (select starts_at>now() from public.basement_slots where id=b.slot_id) then 'booking' else credit_policy end where id=b.id;
    delete from public.gym_checkins where booking_id=b.id;
  else raise exception 'Άγνωστη ενέργεια.'; end if;
end $$;
