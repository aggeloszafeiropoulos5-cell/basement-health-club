create function basement_private.archive_nutrition_plan_version() returns trigger language plpgsql security invoker set search_path=pg_catalog as $$
begin
  if old.content is distinct from new.content or old.status is distinct from new.status or old.title is distinct from new.title then
    insert into public.nutrition_plan_versions(plan_id,member_id,revision,title,starts_on,ends_on,status,content)
    values(old.id,old.member_id,old.revision,old.title,old.starts_on,old.ends_on,old.status,old.content);
  end if;
  return new;
end $$;
revoke all on function basement_private.archive_nutrition_plan_version() from public,anon,authenticated;
create trigger nutrition_plan_archive_version before update on public.nutrition_plans for each row execute function basement_private.archive_nutrition_plan_version();
