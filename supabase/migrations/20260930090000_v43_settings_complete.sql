create or replace function basement_private.member_service_allowed(p_service text,p_day date)
returns boolean language sql stable security definer set search_path='' as $$
 with cfg as(select coalesce(value,'{}') v from public.app_settings where key='control_center_settings'), me as(
  select m.id member_id, m.active, not exists(select 1 from public.member_packages x where x.member_id=m.id) is_new
  from public.profiles pr join public.members m on m.auth_user_id=pr.id
  where pr.id=auth.uid() and pr.active and pr.role='customer'
 )
 select exists(select 1 from public.services sv where lower(sv.name)=lower(p_service) and sv.active and sv.online_booking_enabled)
 and exists(select 1 from me where active or not coalesce((select (v->>'activeCustomersOnly')::boolean from cfg),true))
 and (
  not coalesce((select (v->>'creditsRequired')::boolean from cfg),true)
  or exists(select 1 from me where is_new and coalesce((select (v->>'newCustomerBooking')::boolean from cfg),false)
      and (coalesce((select (v->>'newCustomerOutsideSubscription')::boolean from cfg),false) or coalesce((select (v->>'skipNewCustomerChecks')::boolean from cfg),false)))
  or exists(
    select 1 from me join public.member_packages mp on mp.member_id=me.member_id
    join public.package_templates pt on pt.id=mp.package_template_id
    where mp.status::text in('active','scheduled') and mp.starts_on<=p_day
      and (mp.expires_on>=p_day or not coalesce((select (v->>'blockAfterExpiry')::boolean from cfg),true)
        or mp.expires_on+coalesce((select (v->>'maxAutoExtendDays')::integer from cfg),0)>=p_day)
      and (mp.frozen_until is null or mp.frozen_until<p_day) and pt.online_booking_enabled
      and basement_private.package_covers_service(mp.package_template_id,p_service)
  )
 );
$$;
