alter table public.member_measurements
  add column if not exists height_cm numeric(5,2),
  add column if not exists muscle_mass_kg numeric(5,2),
  add column if not exists visceral_fat numeric(5,2),
  add column if not exists metabolic_age integer,
  add column if not exists bmr_kcal integer;

alter table public.member_measurements
  add constraint member_measurements_height_range check (height_cm is null or height_cm between 80 and 260),
  add constraint member_measurements_muscle_range check (muscle_mass_kg is null or muscle_mass_kg between 0 and 250),
  add constraint member_measurements_visceral_range check (visceral_fat is null or visceral_fat between 0 and 100),
  add constraint member_measurements_metabolic_age_range check (metabolic_age is null or metabolic_age between 1 and 130),
  add constraint member_measurements_bmr_range check (bmr_kcal is null or bmr_kcal between 500 and 6000);
grant usage,select on sequence public.member_measurements_id_seq to authenticated;

